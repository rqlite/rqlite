var (
	// ErrOpenTransaction is returned when the final frame in the WAL file is not a committing frame.
	ErrOpenTransaction = errors.New("open transaction at end of WAL file")
)

// CompactingFrameScanner implements WALIterator to iterate over compacted WAL
// frames starting from a given frame index. It scans all valid frames from the
// start position to the end of the WAL (or the first invalid frame), keeps only
// the latest version of each page (respecting transaction boundaries), and
// returns them in file offset order. If fullScan is false, frame checksums are
// not verified since the WAL file is trusted.
//
// A WAL of 32 + N*(pageSize+24) bytes is reduced to 32 + U*(pageSize+24)
// bytes, where U is the number of unique pages. Each surviving frame reports
// the two cumulative source checksums that bracket it, so the Writer can
// advance its running checksum without reading page data. That holds for a
// resumed scan too: seeding the chain costs one 24-byte frame header read, not
// a page-sized checksum pass.
type CompactingFrameScanner struct {
	readSeeker io.ReadSeeker
	walReader  *Reader
	header     *WALHeader
	fullScan   bool
	start      int64

	// pageBuf is a scratch buffer reused across Next() calls to avoid a
	// page-sized allocation per frame. The Frame returned by Next aliases
	// this buffer in its Data field; see Next's doc comment.
	pageBuf []byte

	frames cFrames
	fIdx   int
}

// NewCompactingFrameScanner creates a new CompactingFrameScanner that reads
// and compacts frames starting at the 0-based startFrame index, scanning to
// the end of the WAL or the first invalid frame. The WAL header is always read
// from offset 0 and is used to determine the page size (and therefore the frame
// size) for offset calculation.
//
// If fullScan is true, the scanner will perform a checksum validation on each frame.
// fullScan requires startFrame to be 0 so that running checksums can be validated
// from the beginning of the WAL.
//
// If fullScan is false, the scanner will only scan the file sufficiently to find the
// last valid frame for each page via a simple salt1 and salt2 match, without performing
// a full checksum validation. This is suitable when the WAL file is trusted (e.g. it's
// just been generated by SQLite and is known a priori to be valid). This can be much
// faster for large WAL files, since it avoids reading the page data for each frame.
//
// Scanning stops at the first invalid frame (e.g. salt mismatch, checksum failure if
// applicable, or partial read).
func NewCompactingFrameScanner(r io.ReadSeeker, startFrame int64, fullScan bool) (*CompactingFrameScanner, error) {
	walReader := NewReader(r)
	if err := walReader.ReadHeader(); err != nil {
		return nil, err
	}

	pageSize := walReader.pageSize
	frameSize := int64(WALFrameHeaderSize) + int64(pageSize)

	if fullScan && startFrame != 0 {
		return nil, fmt.Errorf("fullScan requires startFrame to be 0, got %d", startFrame)
	}
	if startFrame < 0 {
		return nil, fmt.Errorf("startFrame (%d) must not be negative", startFrame)
	}

	s := &CompactingFrameScanner{
		readSeeker: r,
		walReader:  walReader,
		header: &WALHeader{
			Magic:     walReader.magic,
			Version:   WALSupportedVersion,
			PageSize:  pageSize,
			Seq:       walReader.seq,
			Salt1:     walReader.salt1,
			Salt2:     walReader.salt2,
			Checksum1: walReader.chksum1,
			Checksum2: walReader.chksum2,
		},
		fullScan: fullScan,
		start:    WALHeaderSize + startFrame*frameSize,
		pageBuf:  make([]byte, pageSize),
	}

	startT := time.Now()
	n, err := s.scan()
	if err != nil {
		stats.Add(compactScanErrors, 1)
		return nil, err
	}
	recordDuration(compactScanDuration, startT)
	stats.Get(compactFramesOutput).(*expvar.Int).Set(int64(len(s.frames)))
	if len(s.frames) > 0 {
		r := math.Round(float64(n)/float64(len(s.frames))*10) / 10
		stats.Get(compactFramesRatio).(*expvar.Float).Set(r)
	}
	return s, nil
}

// Header returns the WAL header.
func (s *CompactingFrameScanner) Header() (*WALHeader, error) {
	return s.header, nil
}

// Next returns the next compacted frame. Returns io.EOF when all frames
// have been read.
//
// The returned Frame's Data slice is owned by the scanner and is overwritten
// on the next call to Next. Callers that retain a Frame across Next calls
// must copy Data first.
func (s *CompactingFrameScanner) Next() (*Frame, error) {
	if s.fIdx >= len(s.frames) {
		return nil, io.EOF
	}

	cf := s.frames[s.fIdx]
	if _, err := s.readSeeker.Seek(cf.Offset+WALFrameHeaderSize, io.SeekStart); err != nil {
		return nil, err
	}
	if _, err := io.ReadFull(s.readSeeker, s.pageBuf); err != nil {
		return nil, err
	}
	s.fIdx++

	frame := &Frame{
		Pgno:         cf.Pgno,
		Commit:       cf.Commit,
		Data:         s.pageBuf,
		Prev:         cf.prev,
		Source:       cf.src,
		HasChecksums: true,
	}
	return frame, nil
}

// Empty reports whether the scanner has zero frames to deliver.
func (s *CompactingFrameScanner) Empty() bool {
	return len(s.frames) == 0
}

// Bytes returns a byte slice containing the entire contents of the compacted WAL file.
// The byte slice is suitable for writing to a new WAL file. For large WAL files, this
// may consume a lot of memory, so it should be used with care. It's mostly intended for
// use in testing, where the WAL files are small.
func (s *CompactingFrameScanner) Bytes() ([]byte, error) {
	// Serialise through a copy with its own page buffer, so the caller's scan
	// position and the frame data already handed out by Next stay intact.
	cp := *s
	cp.fIdx = 0
	cp.pageBuf = make([]byte, len(s.pageBuf))

	w, err := NewWriter(&cp)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if _, err := w.WriteTo(&buf); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// scan reads all valid frame headers from start to the end of the WAL and
// builds a compacted frame list, keeping only the latest version of each page.
// Only committed transactions are included.
func (s *CompactingFrameScanner) scan() (int64, error) {
	// Seed the output checksum chain with the checksum immediately before the
	// first scanned frame. On a scan from frame zero the WAL header carries it.
	// A resumed scan reads it from the preceding frame header: 24 bytes, versus
	// checksumming that frame's page. A start position past the end of the WAL
	// yields no frames and never uses the seed, so its error is deferred until
	// the scan shows whether any frame was found.
	prev, seedErr := s.checksumBeforeStart()

	// Seek to the start position.
	if _, err := s.readSeeker.Seek(s.start, io.SeekStart); err != nil {
		return 0, fmt.Errorf("seek to start offset %d: %w", s.start, err)
	}

	var buf []byte
	if s.fullScan {
		buf = make([]byte, s.header.PageSize)
	}

	var framesInput int64
	waitingForCommit := false
	txFrames := make(map[uint32]*cFrame)
	frames := make(map[uint32]*cFrame)
	for {
		pgno, commit, err := s.walReader.ReadFrame(buf)
		if err == io.EOF {
			break
		} else if err != nil {
			return 0, err
		}
		framesInput++

		offset := s.start + s.walReader.Offset() - WALHeaderSize

		txFrames[pgno] = &cFrame{
			Pgno:   pgno,
			Commit: commit,
			Offset: offset,
			prev:   prev,
			src:    s.walReader.frameChecksum(),
		}
		prev = s.walReader.frameChecksum()

		if commit == 0 {
			waitingForCommit = true
			continue
		}
		waitingForCommit = false

		maps.Copy(frames, txFrames)
		clear(txFrames)
	}
	stats.Get(compactFramesInput).(*expvar.Int).Set(framesInput)

	if waitingForCommit {
		return framesInput, ErrOpenTransaction
	}
	if framesInput > 0 && seedErr != nil {
		return 0, seedErr
	}

	s.frames = make(cFrames, 0, len(frames))
	for _, frame := range frames {
		s.frames = append(s.frames, frame)
	}
	sort.Sort(s.frames)
	return framesInput, nil
}

// checksumBeforeStart returns the cumulative checksum of the source WAL
// immediately before the first scanned frame. For a scan from frame zero that
// is the checksum in the WAL header; otherwise it is read from the preceding
// frame header.
func (s *CompactingFrameScanner) checksumBeforeStart() ([2]uint32, error) {
	hdrChecksum := [2]uint32{s.header.Checksum1, s.header.Checksum2}
	if s.start == WALHeaderSize {
		return hdrChecksum, nil
	}

	var hdr [WALFrameHeaderSize]byte
	if _, err := s.readSeeker.Seek(s.start-WALFrameHeaderSize-int64(s.header.PageSize), io.SeekStart); err != nil {
		return [2]uint32{}, fmt.Errorf("seek to preceding frame: %w", err)
	}
	if _, err := io.ReadFull(s.readSeeker, hdr[:]); err != nil {
		return [2]uint32{}, fmt.Errorf("read preceding frame header: %w", err)
	}
	if binary.BigEndian.Uint32(hdr[8:]) != s.header.Salt1 || binary.BigEndian.Uint32(hdr[12:]) != s.header.Salt2 {
		return [2]uint32{}, fmt.Errorf("frame before offset %d belongs to a different WAL", s.start)
	}
	return [2]uint32{binary.BigEndian.Uint32(hdr[16:]), binary.BigEndian.Uint32(hdr[20:])}, nil
}

type cFrame struct {
	Pgno   uint32
	Commit uint32
	Offset int64

	// prev and src are the cumulative source checksums immediately before and
	// after this frame, as stored in the input frame header. The Writer uses
	// the pair to advance its own running checksum.
	prev, src [2]uint32
}

type cFrames []*cFrame

func (c cFrames) Len() int           { return len(c) }
func (c cFrames) Less(i, j int) bool { return c[i].Offset < c[j].Offset }
func (c cFrames) Swap(i, j int)      { c[i], c[j] = c[j], c[i] }
