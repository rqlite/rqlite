package wal

// The SQLite WAL checksum is updated 8 bytes at a time. For an 8-byte block
// holding the 32-bit words (x, y), the running checksum (s0, s1) advances as
//
//	s0' = s0 + x + s1
//	s1' = s1 + y + s0'
//
// which is the affine map
//
//	[s0']   [1 1] [s0]   [x    ]
//	[s1'] = [1 2] [s1] + [x + y]
//
// The linear part is therefore A^n after n 8-byte blocks, where
//
//	A = [1 1]
//	    [1 2]
//
// A is invertible over the integers (det(A) = 1), which is what makes it
// possible to derive the checksum of a compacted WAL from the checksums the
// source WAL already contains, without re-checksumming any page data.

// checksumMatrix is a 2x2 matrix in row-major order (a00, a01, a10, a11).
type checksumMatrix [4]uint32

// checksumMatrixPow returns A^n, where A is the matrix describing one 8-byte
// step of the WAL checksum. Arithmetic is modulo 2^32, matching the uint32
// wrapping used by the checksum itself.
//
// The powers of A are Fibonacci numbers, A^n = [[F(2n-1), F(2n)], [F(2n),
// F(2n+1)]], so they are generated by one addition per step. n is fixed per
// scanner and at most 1+pageSize/8, so iterating is simpler than
// exponentiation by squaring and costs nothing at that size.
func checksumMatrixPow(n uint64) checksumMatrix {
	var f, g uint32 = 0, 1 // F(k), F(k+1), starting at k = 0
	for range 2 * n {
		f, g = g, f+g
	}
	// f is F(2n) and g is F(2n+1), so F(2n-1) is g-f.
	return checksumMatrix{g - f, f, f, g}
}

// apply returns a*(v0, v1).
func (a checksumMatrix) apply(v0, v1 uint32) [2]uint32 {
	return [2]uint32{a[0]*v0 + a[1]*v1, a[2]*v0 + a[3]*v1}
}
